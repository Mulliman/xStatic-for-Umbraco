using System.Text;
using System.Text.Json;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using XStatic.AI.Configuration;
using XStatic.Core;
using XStatic.Core.Generator.Db;
using XStatic.Core.Generator.Storage;
using XStatic.Core.Repositories;

namespace XStatic.AI.Audit;

/// <summary>
/// Runs an AI-assisted GEO/SEO audit over generated static HTML pages using <see cref="IChatClient"/>.
/// </summary>
public interface IGeoSeoAuditService
{
    Task<XStaticResult<AiAuditReport>> AuditSiteAsync(
        int staticSiteId,
        AiAuditRequestOptions? requestOptions = null,
        CancellationToken cancellationToken = default);

    string FormatMarkdownReport(AiAuditReport report);
}

public class GeoSeoAuditService : IGeoSeoAuditService
{
    private const string SystemPrompt = """
        You are an expert technical SEO and Generative Engine Optimization (GEO) auditor reviewing a static website generated by xStatic for Umbraco before deployment.
        Analyze the provided deterministic page signals and content excerpts.
        Produce a concise, actionable Markdown review with:
        1. Executive Summary (overall GEO/SEO readiness).
        2. Priority Fixes (grouped by Critical, Warning, and Info — highlight missing titles/meta descriptions, missing image alt text, broken internal links, thin content, and structured data / AI answerability gaps).
        3. GEO Recommendations (entity clarity, JSON-LD opportunities, clear headings/answers for AI search engines).
        Be specific and reference exact page paths from the input. Do not invent pages or links that are not present in the input.
        """;

    private readonly ISitesRepository _sitesRepository;
    private readonly IStaticSiteStorer _staticSiteStorer;
    private readonly IPageSignalExtractor _pageSignalExtractor;
    private readonly IXStaticChatClientResolver _chatClientResolver;
    private readonly IOptions<XStaticAIOptions> _aiOptions;
    private readonly ILogger<GeoSeoAuditService> _logger;

    public GeoSeoAuditService(
        ISitesRepository sitesRepository,
        IStaticSiteStorer staticSiteStorer,
        IPageSignalExtractor pageSignalExtractor,
        IXStaticChatClientResolver chatClientResolver,
        IOptions<XStaticAIOptions> aiOptions,
        ILogger<GeoSeoAuditService> logger)
    {
        _sitesRepository = sitesRepository ?? throw new ArgumentNullException(nameof(sitesRepository));
        _staticSiteStorer = staticSiteStorer ?? throw new ArgumentNullException(nameof(staticSiteStorer));
        _pageSignalExtractor = pageSignalExtractor ?? throw new ArgumentNullException(nameof(pageSignalExtractor));
        _chatClientResolver = chatClientResolver ?? throw new ArgumentNullException(nameof(chatClientResolver));
        _aiOptions = aiOptions ?? throw new ArgumentNullException(nameof(aiOptions));
        _logger = logger ?? throw new ArgumentNullException(nameof(logger));
    }

    public async Task<XStaticResult<AiAuditReport>> AuditSiteAsync(
        int staticSiteId,
        AiAuditRequestOptions? requestOptions = null,
        CancellationToken cancellationToken = default)
    {
        var site = _sitesRepository.Get<SiteConfig>(staticSiteId);
        if (site is null)
        {
            return XStaticResult<AiAuditReport>.Error($"Site config not found for ID {staticSiteId}.");
        }

        var storagePath = _staticSiteStorer.GetStorageLocationOfSite(staticSiteId);
        if (string.IsNullOrWhiteSpace(storagePath) || !Directory.Exists(storagePath))
        {
            return XStaticResult<AiAuditReport>.Error(
                $"No generated static output found at '{storagePath}'. Generate the site before running the AI audit.");
        }

        var options = _aiOptions.Value;
        var profileAlias = !string.IsNullOrWhiteSpace(requestOptions?.ProfileAlias)
            ? requestOptions.ProfileAlias
            : options.ProfileAlias;

        var chatClient = _chatClientResolver.Resolve(profileAlias);
        if (chatClient is null)
        {
            return XStaticResult<AiAuditReport>.Error(
                "No Microsoft.Extensions.AI IChatClient is configured. Register an IChatClient in DI or configure an Umbraco.AI chat client factory via AddXStaticAIChatClient.");
        }

        var maxPages = requestOptions?.MaxPages is > 0
            ? requestOptions.MaxPages.Value
            : options.DefaultMaxPagesToAudit;
        var maxChars = requestOptions?.MaxCharactersPerPage is > 0
            ? requestOptions.MaxCharactersPerPage.Value
            : options.MaxCharactersPerPage;
        var thinThreshold = requestOptions?.ThinContentWordThreshold is > 0
            ? requestOptions.ThinContentWordThreshold.Value
            : options.ThinContentWordThreshold;

        var snapshots = _pageSignalExtractor.ExtractFromDirectory(
            storagePath,
            maxPages,
            maxChars,
            thinThreshold,
            requestOptions?.IncludePathPrefixes,
            out var totalDiscovered);

        if (snapshots.Count == 0)
        {
            return XStaticResult<AiAuditReport>.Error(
                "No HTML pages were found in the generated site output to audit.");
        }

        var allIssues = snapshots.SelectMany(s => s.DeterministicIssues).ToList();
        var userPrompt = BuildAuditPrompt(site, snapshots, totalDiscovered);

        try
        {
            var messages = new List<ChatMessage>
            {
                new(ChatRole.System, SystemPrompt),
                new(ChatRole.User, userPrompt)
            };

            var response = await chatClient.GetResponseAsync(messages, cancellationToken: cancellationToken)
                .ConfigureAwait(false);

            var aiSummary = string.IsNullOrWhiteSpace(response.Text)
                ? "_No AI summary was returned by the configured chat model._"
                : response.Text.Trim();

            var report = new AiAuditReport(
                StaticSiteId: site.Id,
                SiteName: site.Name ?? $"Site {site.Id}",
                GeneratedAtUtc: DateTimeOffset.UtcNow,
                TotalHtmlFilesDiscovered: totalDiscovered,
                AuditedPageCount: snapshots.Count,
                CriticalIssueCount: allIssues.Count(i => i.Severity == AuditSeverity.Critical),
                WarningIssueCount: allIssues.Count(i => i.Severity == AuditSeverity.Warning),
                Pages: snapshots,
                Issues: allIssues,
                AiSummaryMarkdown: aiSummary,
                ModelId: response.ModelId);

            return XStaticResult<AiAuditReport>.Success(report);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "AI GEO/SEO audit failed for site {SiteId}", staticSiteId);
            return XStaticResult<AiAuditReport>.Error($"AI GEO/SEO audit failed: {ex.Message}", ex);
        }
    }

    public string FormatMarkdownReport(AiAuditReport report)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# xStatic AI Pre-Deploy GEO/SEO Audit: {report.SiteName}");
        sb.AppendLine();
        sb.AppendLine($"- **Site ID:** {report.StaticSiteId}");
        sb.AppendLine($"- **Generated (UTC):** {report.GeneratedAtUtc:yyyy-MM-dd HH:mm:ss}Z");
        sb.AppendLine($"- **Pages Audited:** {report.AuditedPageCount} of {report.TotalHtmlFilesDiscovered} HTML files");
        sb.AppendLine($"- **Critical Issues:** {report.CriticalIssueCount}");
        sb.AppendLine($"- **Warnings:** {report.WarningIssueCount}");
        if (!string.IsNullOrWhiteSpace(report.ModelId))
        {
            sb.AppendLine($"- **Model:** `{report.ModelId}`");
        }

        sb.AppendLine();
        sb.AppendLine("## Deterministic Findings");
        sb.AppendLine();

        if (report.Issues.Count == 0)
        {
            sb.AppendLine("No deterministic SEO/GEO issues were detected across the audited pages.");
        }
        else
        {
            sb.AppendLine("| Severity | Page | Category | Details |");
            sb.AppendLine("| --- | --- | --- | --- |");
            foreach (var issue in report.Issues.OrderByDescending(i => i.Severity).ThenBy(i => i.PagePath, StringComparer.OrdinalIgnoreCase))
            {
                sb.AppendLine($"| {issue.Severity} | `{issue.PagePath}` | {issue.Category} | {EscapeMarkdownCell(issue.Message)} |");
            }
        }

        sb.AppendLine();
        sb.AppendLine("## AI GEO/SEO Review");
        sb.AppendLine();
        sb.AppendLine(report.AiSummaryMarkdown);

        return sb.ToString();
    }

    private static string BuildAuditPrompt(
        SiteConfig site,
        IReadOnlyList<PageAuditSnapshot> snapshots,
        int totalDiscovered)
    {
        var payload = new
        {
            siteId = site.Id,
            siteName = site.Name,
            targetHostname = site.TargetHostname,
            totalHtmlFilesDiscovered = totalDiscovered,
            auditedPageCount = snapshots.Count,
            pages = snapshots.Select(p => new
            {
                path = p.RelativePath,
                title = p.Title,
                metaDescription = p.MetaDescription,
                canonicalUrl = p.CanonicalUrl,
                h1Count = p.H1Count,
                primaryH1 = p.PrimaryH1,
                totalImageCount = p.TotalImageCount,
                imagesMissingAltCount = p.ImagesMissingAltCount,
                wordCount = p.WordCount,
                hasJsonLdStructuredData = p.HasJsonLdStructuredData,
                hasOpenGraphTags = p.HasOpenGraphTags,
                brokenInternalLinks = p.BrokenInternalLinks,
                deterministicIssues = p.DeterministicIssues.Select(i => new { severity = i.Severity.ToString(), i.Category, i.Message }),
                excerpt = p.PlainTextExcerpt
            })
        };

        var json = JsonSerializer.Serialize(payload, new JsonSerializerOptions { WriteIndented = true });
        return $"Audit the following generated static site pages prior to deployment:\n\n```json\n{json}\n```";
    }

    private static string EscapeMarkdownCell(string value) =>
        value.Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");
}
